describe('shortenBlogTitle', () => {
  it.each(REAL_TITLES)('%s', (title, expected) => {
    expect(shortenBlogTitle(title)).toBe(expected);
  });

  it('keeps every real title within 24 characters', () => {
    for (const [title] of REAL_TITLES) {
      expect(shortenBlogTitle(title).length).toBeLessThanOrEqual(24);
    }
  });

  it('leaves titles in an unknown format readable (tags removed only)', () => {
    expect(shortenBlogTitle('[출장바베큐] 겨울 캠핑 바베큐 이야기')).toBe('겨울 캠핑 바베큐 이야기');
    expect(shortenBlogTitle('완전히 다른 형식의 제목')).toBe('완전히 다른 형식의 제목');
  });

  it('falls back to the original title when the result would be too short', () => {
    expect(shortenBlogTitle('[출장바베큐] 후기')).toBe('[출장바베큐] 후기');
    expect(shortenBlogTitle('[출장바베큐]')).toBe('[출장바베큐]');
  });
});
